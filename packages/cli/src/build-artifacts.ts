import { readFile, rm, writeFile } from 'node:fs/promises';
import type { Platform } from '@package-broker/core/plugin';
import type { MigrationSource } from '@package-broker/db-sqlite/migrations/source';

export const GENERATED_PACKAGE_MARKER = 'pbGenerated';

export interface BuildInfo {
  readonly schemaVersion: 1;
  readonly target: Platform;
  readonly core: string;
  readonly plugins: Readonly<Record<string, string>>;
  readonly lockfileSha256: string | null;
  readonly gitSha: string | null;
}

export function renderBuildInfo(info: BuildInfo): string {
  return `${JSON.stringify(info, null, 2)}\n`;
}

export function renderNodePackageJson(betterSqliteVersion: string): string {
  return `${JSON.stringify(
    {
      name: 'package-broker-node',
      private: true,
      type: 'module',
      [GENERATED_PACKAGE_MARKER]: true,
      dependencies: { 'better-sqlite3': betterSqliteVersion },
    },
    null,
    2,
  )}\n`;
}

async function readGeneratedPackageJson(
  packageJsonPath: string,
): Promise<Record<string, unknown> | null> {
  let contents: string;
  try {
    contents = await readFile(packageJsonPath, 'utf8');
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT') return null;
    throw error;
  }
  try {
    const parsed: unknown = JSON.parse(contents);
    return typeof parsed === 'object' && parsed !== null ? (parsed as Record<string, unknown>) : {};
  } catch {
    return {};
  }
}

export async function writeOutputPackageJson(
  packageJsonPath: string,
  contents: string | null,
): Promise<void> {
  const existing = await readGeneratedPackageJson(packageJsonPath);
  if (existing !== null && existing[GENERATED_PACKAGE_MARKER] !== true) {
    throw new Error(
      `refusing to ${
        contents === null ? 'remove' : 'overwrite'
      } ${packageJsonPath}: it exists but was not generated by pb; pass --out with another directory`,
    );
  }
  if (contents === null) {
    await rm(packageJsonPath, { force: true });
    return;
  }
  await writeFile(packageJsonPath, contents);
}

export function renderBuildManifest(
  configPath: string,
  migrations?: readonly MigrationSource[],
  platform: NodeJS.Platform = process.platform,
): string {
  const specifier = platform === 'win32' ? configPath.replaceAll('\\', '/') : configPath;
  const lines = [
    `import config from ${JSON.stringify(specifier)};`,
    'export const plugins = config.plugins;',
  ];
  if (migrations !== undefined) {
    lines.push(`export const migrations = ${JSON.stringify(migrations, null, 2)};`);
  }
  return `${lines.join('\n')}\n`;
}
