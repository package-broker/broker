import type { IdempotencyRecord } from '../api/idempotency.js';
import type { AuditEvent } from '../audit/actions.js';
import type { MutationFence } from '../authz/fence.js';
import type { OrgContext } from './port.js';

/** `authority`: the actor's live authority failed inside the batch. `conflict`: the expected role revision is stale. `indeterminate`: the response was lost and the batch may have committed. */
export type FencedRoleFailure = 'authority' | 'conflict' | 'indeterminate';

export const ROLE_KEY_PATTERN = /^[a-z][a-z0-9_]{0,63}$/;

export const ROLE_NAME_MAX_LENGTH = 100;

export interface Role {
  readonly id: string;
  readonly key: string;
  readonly name: string;
  readonly scope: 'organization' | 'project';
  readonly isSystem: boolean;
  readonly protectsLastHolder: boolean;
  readonly revision: number;
  readonly permissions: readonly string[];
}

type MutationInput = { readonly audit?: AuditEvent; readonly idempotency?: IdempotencyRecord };

export interface RoleRepository {
  list(ctx: OrgContext): Promise<Role[]>;
  get(ctx: OrgContext, id: string): Promise<Role | null>;
  /**
   * Every mutator runs as one fenced batch: it re-reads the actor (`fence.userId`, status, session
   * `fence.sessionId`, ownership, `org:roles:write`) and checks the old and requested permission
   * sets against the actor's live permissions with database time, and rename, setPermissions and
   * delete also compare `fence.expected.role` with `role.revision` (TypeError when absent). Every
   * actual role or role_permission change increments `role.revision` once.
   *
   * Never sets `protects_last_holder` and never touches an existing role. `id` and `now` must be
   * generated by the server for each call: replaying identical input (same id, key, name, scope and
   * `now`) against a custom role that still has no permissions fills in the requested permissions.
   * Rejects an invalid key
   * or name with TypeError before SQL. A key reserved for a default role answers `duplicate_key`
   * without SQL. `invalid_permissions` (nothing written): a name outside the catalogue, or an
   * `org:*` name on a project role.
   */
  create(
    ctx: OrgContext,
    fence: MutationFence,
    input: MutationInput & {
      readonly id: string;
      readonly key: string;
      readonly name: string;
      readonly scope: 'organization' | 'project';
      readonly permissions: readonly string[];
      readonly now: string;
      readonly opId: string;
    },
  ): Promise<'created' | 'duplicate_key' | 'invalid_permissions' | 'authority' | 'indeterminate'>;
  /**
   * `locked` for a role that protects the last holder. Rejects a name of 0 or more than 100 code
   * points, or one holding control, format, line or paragraph separator characters or a lone
   * surrogate, with TypeError before SQL.
   */
  rename(
    ctx: OrgContext,
    fence: MutationFence,
    input: MutationInput & {
      readonly id: string;
      readonly name: string;
      readonly now: string;
      readonly opId: string;
    },
  ): Promise<'renamed' | 'not_found' | 'locked' | FencedRoleFailure>;
  /**
   * Replaces the permission set in one batch; `locked` for a role that protects the last holder.
   * `invalid_permissions` (nothing written): a name outside the catalogue, or an `org:*` name on a
   * project role.
   */
  setPermissions(
    ctx: OrgContext,
    fence: MutationFence,
    input: MutationInput & {
      readonly id: string;
      readonly permissions: readonly string[];
      readonly now: string;
      readonly opId: string;
    },
  ): Promise<'updated' | 'not_found' | 'locked' | 'invalid_permissions' | FencedRoleFailure>;
  delete(
    ctx: OrgContext,
    fence: MutationFence,
    input: MutationInput & {
      readonly id: string;
      readonly opId: string;
    },
  ): Promise<'deleted' | 'not_found' | 'system' | 'in_use' | FencedRoleFailure>;
}
