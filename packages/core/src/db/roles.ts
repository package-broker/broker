import type { OrgContext } from './port.js';

export const ROLE_KEY_PATTERN = /^[a-z][a-z0-9_]{0,63}$/;

export const ROLE_NAME_MAX_LENGTH = 100;

export interface Role {
  readonly id: string;
  readonly key: string;
  readonly name: string;
  readonly scope: 'organization' | 'project';
  readonly isSystem: boolean;
  readonly protectsLastHolder: boolean;
  readonly permissions: readonly string[];
}

export interface RoleRepository {
  list(ctx: OrgContext): Promise<Role[]>;
  get(ctx: OrgContext, id: string): Promise<Role | null>;
  /**
   * Never sets `protects_last_holder` and never touches an existing role. `id` and `now` must be
   * generated by the server for each call: replaying identical input (same id, key, name, scope and
   * `now`) against a custom role that still has no permissions fills in the requested permissions.
   * Rejects an invalid key
   * or name with TypeError before SQL. A key reserved for a default role answers `duplicate_key`
   * without SQL. `invalid_permissions` (nothing written): a name outside the catalogue, or an
   * `org:*` name on a project role.
   */
  create(
    ctx: OrgContext,
    input: {
      readonly id: string;
      readonly key: string;
      readonly name: string;
      readonly scope: 'organization' | 'project';
      readonly permissions: readonly string[];
      readonly now: string;
    },
  ): Promise<'created' | 'duplicate_key' | 'invalid_permissions'>;
  /**
   * `locked` for a role that protects the last holder. Rejects a name of 0 or more than 100 code
   * points, or one holding control, format, line or paragraph separator characters or a lone
   * surrogate, with TypeError before SQL.
   */
  rename(
    ctx: OrgContext,
    id: string,
    name: string,
    now: string,
  ): Promise<'renamed' | 'not_found' | 'locked'>;
  /**
   * Replaces the permission set in one batch; `locked` for a role that protects the last holder.
   * `invalid_permissions` (nothing written): a name outside the catalogue, or an `org:*` name on a
   * project role.
   */
  setPermissions(
    ctx: OrgContext,
    id: string,
    permissions: readonly string[],
    now: string,
  ): Promise<'updated' | 'not_found' | 'locked' | 'invalid_permissions'>;
  delete(ctx: OrgContext, id: string): Promise<'deleted' | 'not_found' | 'system' | 'in_use'>;
}
