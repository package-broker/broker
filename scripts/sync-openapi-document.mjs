import { readFile, writeFile } from 'node:fs/promises';
import { format } from 'prettier';

const document = await readFile(new URL('../packages/ui/openapi.json', import.meta.url), 'utf8');
const source = `// Generated by pnpm openapi:sync.
import type { OpenApiDocument } from './openapi.js';

export const openApiDocument = JSON.parse(${JSON.stringify(document)}) as OpenApiDocument;
`;
await writeFile(
  new URL('../packages/core/src/api/openapi-document.ts', import.meta.url),
  await format(source, { parser: 'typescript', singleQuote: true }),
);
